export function getArtifactTemplates(namespaceId: string, orgId: string): ArtifactTemplate[] {
  const filePath = getTemplatesPath(namespaceId, orgId);
  if (!existsSync(filePath)) {
    return getDefaultTemplates();
  }
  try {
    const raw = readFileSync(filePath, "utf-8");
    const data = JSON.parse(raw) as ArtifactTemplatesFile;
    return data.templates;
  } catch {
    return getDefaultTemplates();
  }
}

export function getArtifactTemplate(
  namespaceId: string,
  orgId: string,
  templateId: string
): ArtifactTemplate | null {
  const all = getArtifactTemplates(namespaceId, orgId);
  return all.find((t) => t.id === templateId) ?? null;
}

export function saveArtifactTemplates(
  namespaceId: string,
  orgId: string,
  templates: ArtifactTemplate[]
): void {
  const filePath = getTemplatesPath(namespaceId, orgId);
  const dir = path.dirname(filePath);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
  const data: ArtifactTemplatesFile = { templates };
  writeFileSync(filePath, JSON.stringify(data, null, 2));
}
