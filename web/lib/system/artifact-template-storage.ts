import { existsSync, readFileSync, writeFileSync, mkdirSync } from "fs";
import path from "path";
import { orgPath } from "../config";
import type { ArtifactType } from "../types";

// ArtifactType lives canonically in ./types; re-export keeps the existing
// "@/lib/artifact-template-storage" import path working for consumers.
export type { ArtifactType };

export const ARTIFACT_TYPE_EXT: Record<ArtifactType, string> = {
  markdown: ".md",
  json: ".json",
  code: ".txt",
  patch: ".patch",
  csv: ".csv",
  text: ".txt",
  image: ".png",
};

export interface ArtifactTemplate {
  id: string;
  name: string;
  type: ArtifactType;
  description: string;
  content: string;
  updatedAt: string;
}

interface ArtifactTemplatesFile {
  templates: ArtifactTemplate[];
}

function getTemplatesPath(namespaceId: string, orgId: string): string {
  return orgPath(namespaceId, orgId, "artifact-templates.json");
}

