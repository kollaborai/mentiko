import {
  RUNNER_LINEAGE_BY_SHAPE_ID,
  type RunnerContractLineage,
} from "./runner-lineage";
import {
  MIGRATION_CLAIM_BY_SHAPE_ID,
  type MigrationClaim,
} from "./migration-claims";

export type DataShapeScope = "global" | "namespace" | "organization" | "project" | "run" | "external";
export type DataShapeFormat = "json" | "jsonl" | "key-value" | "sqlite" | "text" | "mixed";
export type DataShapeAssurance = "enforced" | "drift-checked" | "typed" | "observed" | "open";
export type DataShapeRoot = "global" | "namespace" | "organization" | "project";

export interface DataShapeSampleSpec {
  root: DataShapeRoot;
  patterns: string[][];
  excludePatterns?: string[][];
  format: Exclude<DataShapeFormat, "mixed">;
  valuePath?: string;
  schemaPointer?: string;
}

export interface DataShapeDefinition {
  id: string;
  name: string;
  category: "core" | "runner" | "work" | "configuration" | "integrations" | "organization" | "system";
  description: string;
  scope: DataShapeScope;
  format: DataShapeFormat;
  storage: string[];
  assurance: DataShapeAssurance;
  schemaPath?: string;
  typePaths?: string[];
  validatorPaths?: string[];
  writers: string[];
  readers: string[];
  samples?: DataShapeSampleSpec;
  sensitive?: boolean;
  notes?: string[];
  runnerLineage?: RunnerContractLineage;
  /** Advisory: an agent is actively migrating this shape. See migration-claims.ts. */
  migrationClaim?: MigrationClaim;
}

/**
 * Direct shell sources that currently own some part of a persisted shape's
 * read/write/type/validation contract. This is the general migration queue;
 * runnerLineage remains the more precise lifecycle-surface model for runner
 * contracts. A shell command invoked by typed code is not listed unless that
 * shell file itself appears as a shape owner in the catalog.
 */
export function dataShapeShellSources(
  definition: Pick<DataShapeDefinition, "writers" | "readers" | "typePaths" | "validatorPaths">,
): string[] {
  return Array.from(new Set([
    ...definition.writers,
    ...definition.readers,
    ...(definition.typePaths ?? []),
    ...(definition.validatorPaths ?? []),
  ].filter((path) => /\.sh$/.test(path)))).sort();
}

function shape(definition: DataShapeDefinition): DataShapeDefinition {
  const runnerLineage = RUNNER_LINEAGE_BY_SHAPE_ID[definition.id];
  const migrationClaim = MIGRATION_CLAIM_BY_SHAPE_ID[definition.id];
  return {
    ...definition,
    ...(runnerLineage ? { runnerLineage } : {}),
    ...(migrationClaim ? { migrationClaim } : {}),
  };
}

